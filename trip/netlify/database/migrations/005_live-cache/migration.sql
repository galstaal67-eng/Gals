-- מטמון למקורות המידע החיצוניים.
--
-- שתי סיבות לשמור את זה במסד ולא בזיכרון הפונקציה: פונקציה חסרת־מצב
-- מתחילה קרה בכל קריאה, ושני טלפונים שפותחים את האפליקציה באותו בוקר
-- אמורים לקבל את אותה תשובה בלי לקרוא פעמיים לכל שירות חיצוני.
--
-- המפתח נושא את סוג המקור ואת הטיול: "live:tbilisi-2026", "brief:tbilisi-2026".
-- אין כאן נתוני משתמש — רק תחזיות, חגים ושערי מטבע שחוזרים משירותים
-- ציבוריים, ולכן אין גם מה למחוק כשטיול נמחק.

CREATE TABLE IF NOT EXISTS live_cache (
  key         TEXT PRIMARY KEY,
  doc         JSONB        NOT NULL,
  fetched_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ניקוי שורות ישנות הוא זול כאן, אבל אינדקס על הזמן מאפשר לעשות אותו
-- בלי סריקה מלאה כשיצטברו טיולים
CREATE INDEX IF NOT EXISTS live_cache_age_idx ON live_cache (fetched_at);
